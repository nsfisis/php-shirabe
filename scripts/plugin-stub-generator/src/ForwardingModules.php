<?php

declare(strict_types=1);

namespace Shirabe\PluginStubGenerator;

/**
 * Emits `crates/shirabe/src/php_worker/rpc/forwarding.rs`: one Rust module per worker-side class
 * that forwards members to the Rust side, laid out by the class's namespace the way the porting
 * rules lay out files (`Composer\Package\Locker` is `package::locker`, `Shirabe\RustPluginStub`
 * is `shirabe::rust_plugin_stub`).
 *
 * Each module holds `PhpClass`, a marker type standing for the class. The entity declarations on
 * the Rust side (`php_entity!`, `php_statics!`) implement `ForwardedClass` for it and generate the
 * dispatch of the class's methods; the two routing tables here reach a class's constructor and
 * static methods through that impl, so a class missing one is a compile error.
 */
final class ForwardingModules
{
    private const KEYWORDS = [
        'as', 'async', 'await', 'break', 'const', 'continue', 'dyn', 'else', 'enum', 'extern',
        'false', 'fn', 'for', 'gen', 'if', 'impl', 'in', 'let', 'loop', 'match', 'mod', 'move', 'mut',
        'pub', 'ref', 'return', 'static', 'struct', 'trait', 'true', 'try', 'type', 'unsafe', 'use',
        'where', 'while', 'abstract', 'become', 'box', 'do', 'final', 'macro', 'override', 'priv',
        'typeof', 'unsized', 'virtual', 'yield',
    ];

    /**
     * @param array<string, array{
     *     guard: bool,
     *     parent: ?string,
     *     abstract: bool,
     *     methods: list<array{name: string}>,
     *     statics: list<array{name: string}>,
     *     constructor: ?array{},
     * }> $classes the forwarding classes; `parent` is set only when the parent forwards too
     */
    public function __construct(private readonly array $classes)
    {
        foreach ($classes as $fqcn => $class) {
            if (!$class['guard'] && $this->instanceSurface($fqcn) === []) {
                throw new GenerationError(["$fqcn forwards no instance method"]);
            }
            $names = [];
            foreach (array_merge($class['methods'], $class['statics']) as $member) {
                $this->claim($names, $fqcn, $member['name']);
            }
        }
    }

    /** A PHP member or class name as a Rust identifier: snake case, raw if it is a keyword. */
    public static function rustName(string $name): string
    {
        $snake = strtolower(preg_replace(
            ['/([A-Z]+)([A-Z][a-z])/', '/([a-z0-9])([A-Z])/'],
            ['$1_$2', '$1_$2'],
            $name,
        ));

        return in_array($snake, self::KEYWORDS, true) ? 'r#' . $snake : $snake;
    }

    /** @return list<string> the module path of a class */
    public static function modulePath(string $fqcn): array
    {
        $segments = explode('\\', $fqcn);
        if ($segments[0] === 'Composer') {
            array_shift($segments);
        }

        return array_map(static fn (string $segment): string => self::rustName($segment), $segments);
    }

    public function render(): string
    {
        $tree = [];
        $fqcns = array_keys($this->classes);
        sort($fqcns, SORT_STRING);
        foreach ($fqcns as $fqcn) {
            $node = &$tree;
            foreach (self::modulePath($fqcn) as $segment) {
                $node['children'][$segment] ??= [];
                $node = &$node['children'][$segment];
            }
            if (isset($node['class'])) {
                throw new GenerationError(["$fqcn and {$node['class']} map to the same Rust module"]);
            }
            $node['class'] = $fqcn;
            unset($node);
        }

        $code = "//! Generated by scripts/plugin-stub-generator/generate-stubs from the classifier report; do not\n"
            . "//! edit by hand. One module per worker-side class that forwards members to the Rust side, with\n"
            . "//! the marker type the Rust side's entity declarations implement `ForwardedClass` for.\n\n"
            . "use crate::php_worker::rpc::entity::{Call, ForwardedClass as _, protocol_violation};\nuse crate::php_worker::rpc::forwarding;\n"
            . "use bstr::{BStr, ByteSlice as _};\n"
            . "use shirabe_php_rpc::{PhpThrow, RpcValue};\n\n"
            . $this->construct() . "\n" . $this->callStatic();
        foreach ($tree['children'] ?? [] as $segment => $child) {
            $code .= "\n" . $this->module($segment, $child);
        }

        return self::rustfmt(self::indent($code));
    }

    /** @param array{children?: array<string, mixed>, class?: string} $node */
    private function module(string $segment, array $node): string
    {
        $code = "pub(crate) mod $segment {\n";
        if (isset($node['class'])) {
            $code .= $this->classItems($node['class']);
        }
        foreach ($node['children'] ?? [] as $child => $grandchild) {
            $code .= $this->module($child, $grandchild);
        }

        return $code . "}\n";
    }

    /** A `NewObject` from the worker: builds the entity, registers it and answers its Rust entity id. */
    private function construct(): string
    {
        $arms = '';
        foreach ($this->sorted() as $fqcn) {
            if ($this->classes[$fqcn]['constructor'] === null) {
                continue;
            }
            $arms .= self::byteString($fqcn) . ' => <' . self::pathOf($fqcn) . "::PhpClass>::construct(call),\n";
        }

        return "/// A `NewObject` from the worker: builds the entity, registers it and answers its Rust entity id.\n"
            . "/// A stub's constructor sends `static::class`, so a plugin's subclass of a proxied class\n"
            . "/// reaches the last arm.\n"
            . "pub(crate) fn construct(class: &BStr, call: &mut Call<'_>) -> Result<u64, PhpThrow> {\n"
            . "match class.as_bytes() {\n{$arms}_ => Err(call.unconstructible()),\n}\n}\n";
    }

    /** A `CallStaticMethod` from the worker. */
    private function callStatic(): string
    {
        $arms = '';
        foreach ($this->sorted() as $fqcn) {
            if ($this->classes[$fqcn]['statics'] !== []) {
                $arms .= self::byteString($fqcn) . ' => <' . self::pathOf($fqcn) . "::PhpClass>::call_static(call),\n";
            }
        }

        return "/// A `CallStaticMethod` from the worker. A static forwarder sends `self::class`, so the class\n"
            . "/// is always one that declares the method.\n"
            . "pub(crate) fn call_static(class: &BStr, call: &mut Call<'_>) -> Result<RpcValue, PhpThrow> {\n"
            . "match class.as_bytes() {\n{$arms}_ => protocol_violation(call),\n}\n}\n";
    }

    private function classItems(string $fqcn): string
    {
        $what = $this->classes[$fqcn]['guard'] ? ', whose static methods are forwarded' : '';

        return "/// `$fqcn`$what.\n#[derive(Debug)]\npub(crate) struct PhpClass;\n";
    }

    /** @return list<string> */
    private function instanceSurface(string $fqcn): array
    {
        $methods = [];
        for ($class = $fqcn; $class !== null; $class = $this->classes[$class]['parent']) {
            foreach ($this->classes[$class]['methods'] as $method) {
                $methods[$method['name']] = true;
            }
        }

        return array_keys($methods);
    }

    /** @return list<string> */
    private function sorted(): array
    {
        $fqcns = array_keys($this->classes);
        sort($fqcns, SORT_STRING);

        return $fqcns;
    }

    /** @param array<string, true> $names */
    private function claim(array &$names, string $fqcn, string $member): string
    {
        $name = self::rustName($member);
        if (isset($names[$name])) {
            throw new GenerationError(["$fqcn: two members map to the Rust name $name"]);
        }
        $names[$name] = true;

        return $name;
    }

    private static function pathOf(string $fqcn): string
    {
        return 'forwarding::' . implode('::', self::modulePath($fqcn));
    }


    private static function byteString(string $value): string
    {
        return 'b"' . addcslashes($value, "\\\"") . '"';
    }


    /**
     * Indents the code by its brace depth. rustfmt leaves an item it cannot fit in its maximum
     * width as it is, so the code must already be indented when it reaches rustfmt.
     */
    private static function indent(string $code): string
    {
        $depth = 0;
        $lines = [];
        foreach (explode("\n", $code) as $line) {
            $closing = strspn($line, '}');
            $lines[] = $line === '' ? '' : str_repeat('    ', $depth - $closing) . $line;
            $depth += substr_count($line, '{') - substr_count($line, '}');
        }
        if ($depth !== 0) {
            throw new GenerationError(['unbalanced braces in the generated forwarding modules']);
        }

        return implode("\n", $lines);
    }

    private static function rustfmt(string $code): string
    {
        $process = proc_open(
            ['rustfmt', '--edition', '2024'],
            [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']],
            $pipes,
        );
        if (!is_resource($process)) {
            throw new GenerationError(['cannot run rustfmt']);
        }
        fwrite($pipes[0], $code);
        fclose($pipes[0]);
        $formatted = stream_get_contents($pipes[1]);
        $errors = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        if (proc_close($process) !== 0) {
            throw new GenerationError(["rustfmt failed on the generated forwarding modules:\n$errors"]);
        }

        return $formatted;
    }
}
